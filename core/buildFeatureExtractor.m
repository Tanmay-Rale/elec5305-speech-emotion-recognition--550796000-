function afe = buildFeatureExtractor(cfg)
fs=cfg.TargetFs;
win=hann(round(cfg.FrameDuration*fs),'periodic');
ov=max(0,length(win)-round(cfg.HopDuration*fs));

afe=audioFeatureExtractor( ...
    SampleRate=fs,Window=win,OverlapLength=ov, ...
    SpectralDescriptorInput="linearSpectrum", ...
    mfcc=true,mfccDelta=true,mfccDeltaDelta=true, ...
    gtcc=true,gtccDelta=true,gtccDeltaDelta=true, ...
    spectralCentroid=true,spectralCrest=true,spectralEntropy=true, ...
    spectralFlatness=true,spectralFlux=true,spectralKurtosis=true, ...
    spectralRolloffPoint=true,spectralSkewness=true,spectralSlope=true, ...
    spectralSpread=true,pitch=true,harmonicRatio=true, ...
    zerocrossrate=true,shortTimeEnergy=true);
end
